@router.websocket("/ws/{job_id}")
async def diagnosis_websocket(
    websocket: WebSocket,
    job_id: str,
):
    """
    Stream real-time diagnosis progress events for a job.

    Authentication:
        ws://host/api/diagnosis/ws/{job_id}?token=<JWT>

    Events:
        - job_status
        - diagnosis_started
        - agent_completed
        - diagnosis_completed
        - diagnosis_failed
    """

    # --------------------------------------------------------
    # 1. Accept the WebSocket connection first
    # --------------------------------------------------------

    await websocket.accept()

    # --------------------------------------------------------
    # 2. Read JWT from query parameter
    # --------------------------------------------------------

    token = websocket.query_params.get("token")

    if not token:
        await websocket.send_json(
            {
                "event": "error",
                "job_id": job_id,
                "message": "Authentication token is required",
            }
        )
        await websocket.close(code=1008)
        return

    # --------------------------------------------------------
    # 3. Validate JWT
    # --------------------------------------------------------

    try:
        payload = decode_access_token(token)

    except Exception:
        await websocket.send_json(
            {
                "event": "error",
                "job_id": job_id,
                "message": "Invalid or expired token",
            }
        )
        await websocket.close(code=1008)
        return

    user_id = payload.get("sub")

    if not user_id:
        await websocket.send_json(
            {
                "event": "error",
                "job_id": job_id,
                "message": "Invalid token subject",
            }
        )
        await websocket.close(code=1008)
        return

    # --------------------------------------------------------
    # 4. Verify job exists
    # --------------------------------------------------------

    job = get_job(job_id)

    if job is None:
        await websocket.send_json(
            {
                "event": "error",
                "job_id": job_id,
                "message": (
                    "Diagnosis job is not available in the "
                    "current server process."
                ),
            }
        )
        await websocket.close(code=1008)
        return

    # --------------------------------------------------------
    # 5. Verify job ownership
    # --------------------------------------------------------

    if job["user_id"] != str(user_id):
        await websocket.send_json(
            {
                "event": "error",
                "job_id": job_id,
                "message": "You are not authorized to access this job",
            }
        )
        await websocket.close(code=1008)
        return

    # --------------------------------------------------------
    # 6. Subscribe to job events
    # --------------------------------------------------------

    event_queue, history = subscribe(job_id)

    try:

        # ----------------------------------------------------
        # Send current job status
        # ----------------------------------------------------

        await websocket.send_json(
            {
                "event": "job_status",
                "job_id": job_id,
                "status": job["status"],
            }
        )

        # ----------------------------------------------------
        # Replay events that happened before connection
        # ----------------------------------------------------

        for event in history:
            await websocket.send_json(event)

        # ----------------------------------------------------
        # If already completed/failed, stop
        # ----------------------------------------------------

        if job["status"] in {
            "completed",
            "failed",
        }:
            return

        # ----------------------------------------------------
        # Wait for live events
        # ----------------------------------------------------

        while True:

            event = await asyncio.to_thread(
                event_queue.get
            )

            await websocket.send_json(event)

            # ------------------------------------------------
            # Stop after final diagnosis event
            # ------------------------------------------------

            if event["event"] in {
                "diagnosis_completed",
                "diagnosis_failed",
            }:
                break

    except WebSocketDisconnect:
        pass

    finally:
        unsubscribe(
            job_id,
            event_queue,
        )